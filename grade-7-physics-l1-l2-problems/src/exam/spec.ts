export const questionSpecs: QuestionSpec[] = allProblems.map((p) => {
  const subparts = subpartsByProblem[p.id] ?? [];
  const maxMarks = subparts.reduce((acc, s) => acc + s.marks, 0);
  return {
    problemId: p.id,
    lessonId: lessonOfProblem(p.id),
    number: p.number,
    title: p.title,
    level: p.level,
    maxMarks,
    subparts,
  };
});

export const allSubparts: SubpartSpec[] = questionSpecs.flatMap((q) => q.subparts);
