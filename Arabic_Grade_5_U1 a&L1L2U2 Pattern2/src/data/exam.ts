type BranchBase = {
  id: string;
  points: number;
  prompt: string;
  explanation: string;
  ref: string;
};

export type Branch =
  | (BranchBase & {
      kind: "single_choice";
      choices: Choice[];
      correctChoiceId: string;
    })
  | (BranchBase & { kind: "true_false"; correct: boolean })
  | (BranchBase & {
      kind: "fill_blank";
      acceptedAnswers: string[];
      placeholder?: string;
      strictHamza?: boolean;
      note?: string;
    })
  | (BranchBase & {
      kind: "multi_select";
      choices: Choice[];
      correctChoiceIds: string[];
      requiredSelections: number;
    })
  | (BranchBase & {
      kind: "classification";
      categories: Category[];
      items: ClassItem[];
    })
  | (BranchBase & { kind: "matching"; pairs: MatchPair[] })
  | (BranchBase & {
      kind: "ordering";
      items: Choice[];
      correctOrderIds: string[];
    });

