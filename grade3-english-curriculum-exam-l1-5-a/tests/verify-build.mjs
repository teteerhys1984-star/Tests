#!/usr/bin/env node
/**
 * Verifies the single-file production build: dist/index.html exists, is one
 * self-contained file (no external requests), contains every inlined picture and
 * both inlined sound effects, and carries the right EXAM_ID and title.
 *
 *   npm run build && node tests/verify-build.mjs
 */
import { readFileSync, existsSync, statSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const dist = resolve(root, "dist/index.html");
const failures = [];
const check = (ok, message) => {
  console.log(`${ok ? "  ✓" : "  ✗"} ${message}`);
  if (!ok) failures.push(message);
};

check(existsSync(dist), "dist/index.html exists");
if (!existsSync(dist)) {
  console.error("Run `npm run build` first.");
  process.exit(1);
}

const html = readFileSync(dist, "utf8");
check(statSync(dist).size > 500_000, `dist/index.html is a single bundled file (${(statSync(dist).size / 1024).toFixed(0)} kB)`);
check(html.includes("grade3-english-curriculum-exam-l1-5-a"), "EXAM_ID of the published folder is in the bundle");
check(html.includes("Grade 3 English Curriculum Exam L1-5 A"), "pupil-facing exam title is in the bundle");
check(!/src="\.\/assets\/|href="\.\/assets\//.test(html), "no external asset files are referenced");

// No stray local module imports left unresolved in the bundle.
const external = [...html.matchAll(/(?:src|href)="(https?:\/\/[^"]+)"/g)]
  .map((m) => m[1])
  .filter((url) => !url.startsWith("https://wa.me/") && !url.startsWith("https://script.google.com/"));
check(external.length === 0, `no third-party requests (found ${external.length})`);

// Both WAVs are inlined as data URIs (generated by scripts/generate-sounds.mjs).
const wavs = [...html.matchAll(/data:audio\/[a-z0-9.+-]+;base64,[A-Za-z0-9+/=]+/g)];
check(wavs.length >= 2, `both sound effects are inlined (${wavs.length} audio data URIs)`);
const audioBytes = wavs.reduce((sum, m) => sum + m[0].length, 0);
check(audioBytes > 10_000, `inlined audio carries real samples (${audioBytes} base64 chars)`);

// Every picture of the exam is inlined too.
const images = [...html.matchAll(/data:image\/[a-z0-9.+-]+;base64,[A-Za-z0-9+/=]+/g)];
check(images.length >= 3, `curriculum pictures are inlined (${images.length} image data URIs)`);

if (failures.length) {
  console.error(`\n${failures.length} build check(s) failed.`);
  process.exit(1);
}
console.log("\nAll build checks passed.");
