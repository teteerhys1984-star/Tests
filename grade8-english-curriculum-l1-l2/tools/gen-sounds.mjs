/**
 * Generates two original, fully local sounds as 8-bit PCM WAV files:
 *   - start.wav  : short ascending "begin exam" chime
 *   - submit.wav : short completion arpeggio
 * The files are written to public/sounds/ and embedded as base64 data-URIs
 * inside src/audio/soundData.ts so the production build is 100% self-contained
 * (no network / external audio needed at runtime).
 */
import { writeFileSync, mkdirSync } from "fs";

const SAMPLE_RATE = 22050;

/** Render a sequence of notes into a Float32 PCM buffer.
 * note: { freq, start, dur, type, gain } */
function render(totalSec, notes) {
  const n = Math.floor(totalSec * SAMPLE_RATE);
  const buf = new Float32Array(n);
  for (const note of notes) {
    const s0 = Math.floor(note.start * SAMPLE_RATE);
    const s1 = Math.min(n, Math.floor((note.start + note.dur) * SAMPLE_RATE));
    for (let i = s0; i < s1; i++) {
      const t = i / SAMPLE_RATE;
      const local = t - note.start;
      // Attack / release envelope to avoid clicks.
      const atk = Math.min(1, local / 0.02);
      const rel = Math.min(1, (note.dur - local) / 0.09);
      const env = Math.max(0, atk * rel);
      let v = 0;
      const ph = 2 * Math.PI * note.freq * local;
      if (note.type === "sine") v = Math.sin(ph);
      else if (note.type === "triangle")
        v = (2 / Math.PI) * Math.asin(Math.sin(ph));
      else if (note.type === "soft") {
        v = 0.72 * Math.sin(ph) + 0.28 * Math.sin(2 * ph) * Math.exp(-local * 6);
      }
      buf[i] += v * note.gain * env;
    }
  }
  // Soft limiter
  for (let i = 0; i < n; i++) buf[i] = Math.tanh(buf[i] * 1.1);
  return buf;
}

/** Encode Float32 PCM (-1..1) into an 8-bit unsigned WAV file buffer. */
function toWav(floatBuf) {
  const dataSize = floatBuf.length;
  const buffer = Buffer.alloc(44 + dataSize);
  buffer.write("RIFF", 0);
  buffer.writeUInt32LE(36 + dataSize, 4);
  buffer.write("WAVE", 8);
  buffer.write("fmt ", 12);
  buffer.writeUInt32LE(16, 16); // PCM chunk size
  buffer.writeUInt16LE(1, 20); // PCM format
  buffer.writeUInt16LE(1, 22); // mono
  buffer.writeUInt32LE(SAMPLE_RATE, 24);
  buffer.writeUInt32LE(SAMPLE_RATE, 28); // byte rate (8-bit mono)
  buffer.writeUInt16LE(1, 32); // block align
  buffer.writeUInt16LE(8, 34); // bits per sample
  buffer.write("data", 36);
  buffer.writeUInt32LE(dataSize, 40);
  for (let i = 0; i < dataSize; i++) {
    const s = Math.max(-1, Math.min(1, floatBuf[i]));
    buffer.writeUInt8(Math.round((s * 0.5 + 0.5) * 255), 44 + i);
  }
  return buffer;
}

const A5 = 880.0,
  E5 = 659.25,
  FS5 = 739.99,
  C5 = 523.25,
  G5 = 783.99,
  C6 = 1046.5;

// Start: bright two-step ascending chime (E5 -> A5 with sparkle)
const startBuf = render(0.85, [
  { freq: E5, start: 0.0, dur: 0.28, type: "soft", gain: 0.55 },
  { freq: FS5, start: 0.0, dur: 0.28, type: "sine", gain: 0.2 },
  { freq: A5, start: 0.16, dur: 0.4, type: "soft", gain: 0.6 },
  { freq: C6, start: 0.16, dur: 0.4, type: "sine", gain: 0.18 },
]);

// Submit: completion arpeggio C5 - E5 - G5 - C6 with soft tail
const submitBuf = render(1.25, [
  { freq: C5, start: 0.0, dur: 0.22, type: "soft", gain: 0.5 },
  { freq: E5, start: 0.12, dur: 0.24, type: "soft", gain: 0.5 },
  { freq: G5, start: 0.24, dur: 0.3, type: "soft", gain: 0.5 },
  { freq: C6, start: 0.38, dur: 0.62, type: "soft", gain: 0.55 },
  { freq: G5, start: 0.38, dur: 0.62, type: "sine", gain: 0.14 },
]);

mkdirSync("public/sounds", { recursive: true });
mkdirSync("src/audio", { recursive: true });

const wavs = { start: toWav(startBuf), submit: toWav(submitBuf) };
writeFileSync("public/sounds/start.wav", wavs.start);
writeFileSync("public/sounds/submit.wav", wavs.submit);

const b64Start = wavs.start.toString("base64");
const b64Submit = wavs.submit.toString("base64");

writeFileSync(
  "src/audio/soundData.ts",
  `/**
 * AUTO-GENERATED by tools/gen-sounds.mjs — do not edit by hand.
 * Original, fully-local exam sounds embedded as base64 WAV data URIs so the
 * shipped bundle never needs network audio.
 */
export const START_SOUND_DATA_URI =
  "data:audio/wav;base64,${b64Start}";

export const SUBMIT_SOUND_DATA_URI =
  "data:audio/wav;base64,${b64Submit}";
`,
);

console.log(
  `Sounds generated: start.wav=${wavs.start.length}B submit.wav=${wavs.submit.length}B`,
);
