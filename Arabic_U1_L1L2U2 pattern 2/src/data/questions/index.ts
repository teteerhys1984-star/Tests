/* Structural helpers and safe internal checks                                 */
/* -------------------------------------------------------------------------- */

export const QUESTIONS_BY_ID: Record<string, Question> = QUESTIONS.reduce(
  (acc, q) => {
    acc[q.id] = q;
    return acc;
  },
  {} as Record<string, Question>,
);

export const ALL_SUBPARTS = QUESTIONS.flatMap((q) =>
  q.subparts.map((s) => ({ ...s, questionId: q.id, questionNumber: q.number })),
);

export const TOTAL_SUBPARTS = ALL_SUBPARTS.length;
export const TOTAL_MARKS = QUESTIONS.reduce(
  (total, q) => total + q.subparts.reduce((sum, s) => sum + s.marks, 0),
  0,
);

export const questionsForLesson = (lessonId: LessonId) =>
  QUESTIONS.filter((q) => q.lessonId === lessonId);

export function sectionLabel(section: SectionId): string {
  return SECTION_LABELS[section];
}

/** Used by the teacher key and the generated report; never inside the exam UI. */
export function questionReference(question: Question) {
  const lesson = LESSONS_BY_ID[question.lessonId];
  return {
    unit: lesson.unit,
    lessonId: question.lessonId,
    lessonTitle: lesson.title,
    page: question.page,
    section: question.section,
  };
}

// Internal data invariants (helpful while authoring; harmless at runtime).
if (QUESTIONS.length !== 30) {
  throw new Error(`Exam data must contain exactly 30 main questions, found ${QUESTIONS.length}`);
}
if (TOTAL_SUBPARTS < 65 || TOTAL_SUBPARTS > 85) {
  throw new Error(`Exam data must contain 65–85 subparts, found ${TOTAL_SUBPARTS}`);
}
if (TOTAL_MARKS !== 100) {
  throw new Error(`Exam data must total exactly 100 marks, found ${TOTAL_MARKS}`);
}
for (const q of QUESTIONS) {
  const ids = q.subparts.map((s) => s.id);
  if (new Set(ids).size !== ids.length) throw new Error(`Duplicate subpart id in ${q.id}`);
  if (q.section !== "grammar" && q.section !== "spelling") throw new Error("Invalid section");
}

