type SubBase = Omit<Subpart, "kind">;

function single(
  id: string,
  prompt: string,
  options: string[],
  correct: string,
  marks: number,
  explanation: string,
  skill: string,
  misconception?: string,
): Subpart {
  return { id, prompt, kind: "single", options, correct: [correct], marks, explanation, skill, misconception };
}

function multi(
  id: string,
  prompt: string,
  options: string[],
  correct: string[],
  marks: number,
  explanation: string,
  skill: string,
  misconception?: string,
): Subpart {
  return { id, prompt, kind: "multi", options, correct, marks, explanation, skill, misconception };
}

function text(
  id: string,
  prompt: string,
  correct: string[],
  marks: number,
  explanation: string,
  skill: string,
  misconception?: string,
): Subpart {
  return { id, prompt, kind: "text", correct, marks, explanation, skill, misconception };
}

interface QuestionInput {
  id: string;
  number: number;
  lessonId: LessonId;
  section: SectionId;
  difficulty: Difficulty;
  prompt: string;
  context?: string;
  typeLabel: string;
  /** Optional exercise-page reference inside the lesson. */
  page?: number;
  subparts: Subpart[];
}

function question(input: QuestionInput): Question {
  const lesson = LESSONS_BY_ID[input.lessonId];
  return {
    ...input,
    page:
      input.page ?? (input.section === "grammar" ? lesson.grammarPage : lesson.spellingPage),
  };
}

