export function lessonLabel(q: Pick<Question, 'lesson'>): string {
  if (q.lesson === 1) return 'الدرس الأول: الحركة والسكون';
  if (q.lesson === 2) return 'الدرس الثاني: القوة والحركة';
  return 'الدرسان الأول والثاني';
}

export function referenceLine(q: Question): string {
  return `${lessonLabel(q)} — ص ${q.pages} — المهارة: ${q.skill}`;
}

