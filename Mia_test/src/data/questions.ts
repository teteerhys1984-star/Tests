/** Runtime integrity check used by the app and the audit script. */
export function validateExam(): string[] {
  const errors: string[] = [];
  if (questions.length !== 30) errors.push(`عدد الأسئلة ${questions.length} لا يساوي 30`);
  questions.forEach((q) => {
    const sum = q.subparts.reduce((s, sp) => s + sp.marks, 0);
    if (sum !== q.marks) errors.push(`السؤال ${q.id}: مجموع الدرجات ${sum} ≠ ${q.marks}`);
  });
  const total = questions.reduce((s, q) => s + q.marks, 0);
  if (total !== 100) errors.push(`المجموع الكلي ${total} لا يساوي 100`);
  if (allSubparts.length < 65 || allSubparts.length > 80)
    errors.push(`عدد الأجزاء ${allSubparts.length} خارج المجال 65–80`);
  const ids = new Set<string>();
  allSubparts.forEach(({ subpart }) => {
    if (ids.has(subpart.id)) errors.push(`معرّف مكرر: ${subpart.id}`);
    ids.add(subpart.id);
    if (!subpart.page) errors.push(`الجزء ${subpart.id} بلا مرجع صفحة`);
    if (subpart.type === "mcq" && subpart.options) {
      if (!subpart.options.some((o) => o.value === subpart.correct))
        errors.push(`الجزء ${subpart.id}: الإجابة غير موجودة بين الخيارات`);
    }
  });
  return errors;
}
