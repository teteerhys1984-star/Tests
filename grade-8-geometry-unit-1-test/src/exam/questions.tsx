export const TOTAL_MARKS = QUESTIONS.reduce((s, q) => s + q.marks, 0);
export const TOTAL_PARTS = QUESTIONS.reduce((s, q) => s + q.parts.length, 0);

/** Runtime self-check used by the test suite. */
export function verifyBlueprint() {
  const issues: string[] = [];
  if (QUESTIONS.length !== 7) issues.push("عدد الأسئلة الرئيسية ليس ٧");
  if (TOTAL_MARKS !== 100) issues.push(`مجموع العلامات = ${TOTAL_MARKS} وليس ١٠٠`);
  for (const q of QUESTIONS) {
    const sum = q.parts.reduce((s, p) => s + p.marks, 0);
    if (Math.abs(sum - q.marks) > 1e-9)
      issues.push(`مجموع علامات ${q.id} = ${sum} وليس ${q.marks}`);
    for (const p of q.parts) {
      if (p.type === "numeric") {
        const fs = p.fields.reduce((s, f) => s + f.marks, 0);
        if (Math.abs(fs - p.marks) > 1e-9) issues.push(`علامات حقول ${p.id} لا تساوي ${p.marks}`);
      }
      if (p.type === "cloze") {
        const bs = p.pieces.reduce(
          (s, x) => (typeof x === "string" ? s : s + x.blank.marks),
          0,
        );
        if (Math.abs(bs - p.marks) > 1e-9) issues.push(`علامات فراغات ${p.id} لا تساوي ${p.marks}`);
      }
      if (p.type === "tf") {
        const is = p.items.reduce((s, x) => s + x.marks, 0);
        if (Math.abs(is - p.marks) > 1e-9) issues.push(`علامات عبارات ${p.id} لا تساوي ${p.marks}`);
      }
      if (p.type === "plot") {
        const ts = p.targets.reduce((s, x) => s + x.marks, 0);
        if (Math.abs(ts - p.marks) > 1e-9) issues.push(`علامات نقاط ${p.id} لا تساوي ${p.marks}`);
      }
      if (p.type === "mcq" && !p.options.some((o) => o.id === p.correct))
        issues.push(`جواب ${p.id} غير موجود بين الخيارات`);
      if (p.type === "multi")
        for (const c of p.correct)
          if (!p.options.some((o) => o.id === c)) issues.push(`خيار ${c} مفقود في ${p.id}`);
    }
  }
  return issues;
}