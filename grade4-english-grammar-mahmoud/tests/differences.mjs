const ORIGINAL_PRIVACY_LINE = "Generated locally by the exam page. No student answers were sent to a server.";
export const PUBLISHED_PRIVACY_LINE = "Generated by the exam page on the student's device. The result and answers are also sent electronically to the teacher when the test is submitted.";
const INTERNAL_NOTE = / · internal reference: Lesson \d+ > course repository curriculum$/;

/** What the published page must write for a report the original wrote: the two documented changes and nothing else. */
export function toPublishedReport(originalReport) {
  let notes = 0;
  let privacy = 0;
  const lines = originalReport.split("\r\n").map((line) => {
    if (INTERNAL_NOTE.test(line)) { notes += 1; return line.replace(INTERNAL_NOTE, ""); }
    if (line === ORIGINAL_PRIVACY_LINE) { privacy += 1; return PUBLISHED_PRIVACY_LINE; }
    return line;
  });
  if (notes !== 8 || privacy !== 1) throw new Error(`unexpected original report: ${notes} lesson notes, ${privacy} privacy lines`);
  return lines.join("\r\n");
}

/** Line diff (longest common subsequence): which lines were removed from `a` and which were added in `b`. */
export function lineDiff(a, b) {
  const n = a.length;
  const m = b.length;
  const width = m + 1;
  const table = new Uint16Array((n + 1) * width);
  for (let i = n - 1; i >= 0; i--) {
    for (let j = m - 1; j >= 0; j--) {
      table[i * width + j] = a[i] === b[j] ? table[(i + 1) * width + j + 1] + 1 : Math.max(table[(i + 1) * width + j], table[i * width + j + 1]);
    }
  }
  const removed = [];
  const added = [];
  let i = 0;
  let j = 0;
  while (i < n && j < m) {
    if (a[i] === b[j]) { i++; j++; }
    else if (table[(i + 1) * width + j] >= table[i * width + j + 1]) removed.push({ line: i + 1, text: a[i++] });
    else added.push({ line: j + 1, text: b[j++] });
  }
  while (i < n) removed.push({ line: i + 1, text: a[i++] });
  while (j < m) added.push({ line: j + 1, text: b[j++] });
  return { removed, added };
}
